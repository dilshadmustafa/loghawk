def run(input_path: str, output_path: str):
    """
    Execute Stage B for every Stage A feature folder.

    Input:
        s3://loghawk-data/features/2026-09-28/

    Expected children:
        .../container_logs/
        .../loghawk_sample_logs/

    Output:
        s3://loghawk-data/anomalies/2026-09-28/
            container_logs/
                anomaly_results.parquet
            loghawk_sample_logs/
                anomaly_results.parquet
    """
    input_path = normalize_s3_folder(input_path)
    output_path = normalize_s3_folder(output_path)

    identity_mapping_folder = normalize_s3_folder(
        IDENTITY_MAPPING_PATH
    )

    print("=" * 70)
    print("LogHawk Stage B - Folder Processing")
    print("=" * 70)

    print()
    print(f"Input feature folder:")
    print(input_path)

    print()
    print("Identity mapping folder:")
    print(identity_mapping_folder)

    print()
    print("Anomaly output folder:")
    print(output_path)

    fs = get_s3_filesystem()

    feature_folders = list_feature_folders(
        input_path,
        fs,
    )

    print()
    print(f"Feature input folders found: {len(feature_folders)}")

    for index, folder in enumerate(feature_folders, start=1):
        print(f"  {index}. {folder}")

    if not feature_folders:
        raise FileNotFoundError(
            f"No Stage A feature folders found under: {input_path}"
        )

    successful = []
    failed = []

    for index, feature_folder in enumerate(
        feature_folders,
        start=1,
    ):
        print()
        print("#" * 70)
        print(
            f"STAGE B FOLDER {index} OF "
            f"{len(feature_folders)}"
        )
        print("#" * 70)

        try:
            output_file = process_input_folder(
                input_folder=feature_folder,
                output_root=output_path,
                identity_mapping_folder=identity_mapping_folder,
                fs=fs,
            )

            successful.append(
                (
                    feature_folder,
                    output_file,
                )
            )

        except Exception as exc:
            print()
            print(
                f"ERROR processing {feature_folder}:"
            )
            print(f"{type(exc).__name__}: {exc}")
            traceback.print_exc()

            failed.append(
                (
                    feature_folder,
                    str(exc),
                )
            )

    print()
    print("=" * 70)
    print("LogHawk Stage B Folder Run Completed")
    print("=" * 70)

    print(f"Total folders: {len(feature_folders)}")
    print(f"Successful:    {len(successful)}")
    print(f"Failed:        {len(failed)}")

    if successful:
        print()
        print("Successful folders:")

        for input_folder, output_file in successful:
            print(f"  {input_folder}")
            print(f"    -> {output_file}")

    if failed:
        print()
        print("Failed folders:")

        for input_folder, error in failed:
            print(f"  {input_folder}")
            print(f"    {error}")

        raise RuntimeError(
            f"Stage B failed for {len(failed)} "
            f"folder(s)."
        )

    # Return the root output folder because multiple anomaly datasets
    # are now produced.
    return output_path


def _model_registry(model_root: str) -> ModelRegistry:
    return ModelRegistry(normalize_s3_folder(model_root))


def _group_model_paths(
    model_root: str,
    group_name: str,
    backend: str,
    algorithm: str,
) -> dict[str, str]:
    expected_backend, _device = config.anomaly_algorithm_backend_device(algorithm)
    if backend != expected_backend:
        raise ValueError(f"Backend does not match algorithm ID {algorithm!r}")
    return _model_registry(model_root).paths_for_algorithm(group_name, algorithm)


def _s3_key(path: str) -> str:
    return path.replace("s3://", "", 1)


def _save_detector_bundle(
    detector,
    paths: dict[str, str],
    group_name: str,
    calibration_scores: np.ndarray | None,
) -> None:
    fs = get_s3_filesystem()
    for key in ("detector", "scaler", "metadata"):
        fs.makedirs(_s3_key(paths[key]).rsplit("/", 1)[0], exist_ok=True)
    if calibration_scores is not None:
        fs.makedirs(_s3_key(paths["calibration"]).rsplit("/", 1)[0], exist_ok=True)

    print(f"Saving {detector.algorithm} detector to: {paths['detector']}")
    with fs.open(_s3_key(paths["detector"]), "wb") as stream:
        detector.save(stream)

    scaler_buffer = BytesIO()
    np.savez(scaler_buffer, **detector.export_scaler_state())
    with fs.open(_s3_key(paths["scaler"]), "wb") as stream:
        stream.write(scaler_buffer.getvalue())

    calibration_path = None
    if calibration_scores is not None:
        calibration_path = paths["calibration"]
        calibration_buffer = BytesIO()
        np.savez(
            calibration_buffer,
            scores=calibration_reference(calibration_scores),
        )
        with fs.open(_s3_key(calibration_path), "wb") as stream:
            stream.write(calibration_buffer.getvalue())
    elif fs.exists(_s3_key(paths["calibration"])):
        fs.rm(_s3_key(paths["calibration"]))

    versions = {
        "cuml": package_version("cuml"),
        "nvforest": package_version("nvforest"),
        "treelite": package_version("treelite"),
        "scikit-learn": package_version("scikit-learn"),
        "pyod": package_version("pyod"),
        "torch": package_version("torch"),
    }
    metadata = DetectorMetadata(
        backend=detector.backend,
        group=group_name,
        feature_columns=list(ML_FEATURE_COLUMNS),
        detector_path=paths["detector"],
        scaler_path=paths["scaler"],
        backend_metadata=detector.export_backend_metadata(),
        versions=versions,
        capabilities=detector.capabilities.to_dict(),
        algorithm=detector.algorithm,
        detector_type=detector.algorithm,
        calibration_path=calibration_path,
    )
    with fs.open(_s3_key(paths["metadata"]), "w") as stream:
        ModelRegistry.write_metadata(stream, metadata)


def _save_group_artifacts(detector, paths: dict[str, str], group_name: str):
    """Compatibility helper for the standalone, single-detector entry point."""
