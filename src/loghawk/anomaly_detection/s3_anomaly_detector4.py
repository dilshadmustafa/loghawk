def _save_model_set(model_root: str, group_name: str) -> None:
    registry = _model_registry(model_root)
    path = registry.model_set_path(group_name)
    key = _s3_key(path)
    fs = get_s3_filesystem()
    fs.makedirs(key.rsplit("/", 1)[0], exist_ok=True)
    algorithms = list(config.LH_EFFECTIVE_ANOMALY_ALGORITHMS)
    manifest = {
        "manifest_version": 1,
        "group": group_name,
        "algorithms": algorithms,
        "aggregation": "mean_percentile" if len(algorithms) > 1 else "single",
        "threshold": config.LH_ENSEMBLE_THRESHOLD if len(algorithms) > 1 else None,
        "feature_columns": list(ML_FEATURE_COLUMNS),
    }
    with fs.open(key, "w") as stream:
        json.dump(manifest, stream, indent=2)
        stream.write("\n")


def _load_saved_models(model_root: str, group_name: str, fs):
    registry = _model_registry(model_root)
    model_set_path = registry.model_set_path(group_name)
    model_set_key = _s3_key(model_set_path)
    if not fs.exists(model_set_key):
        raise FileNotFoundError(
            "Model-set manifest is missing; run the Stage B Train phase. "
            f"Expected: {model_set_path}"
        )
    with fs.open(model_set_key, "r") as stream:
        model_set = json.load(stream)

    expected_algorithms = list(config.LH_EFFECTIVE_ANOMALY_ALGORITHMS)
    if model_set.get("algorithms") != expected_algorithms:
        raise ValueError(
            "Saved model algorithms do not match the configured list. "
            "Run the Stage B Train phase again."
        )
    if model_set.get("group") != group_name:
        raise ValueError("Saved model-set group does not match the requested group.")
    if model_set.get("feature_columns") != ML_FEATURE_COLUMNS:
        raise ValueError("Saved model-set feature schema does not match Stage B.")

    loaded = []
    for algorithm in expected_algorithms:
        paths = registry.paths_for_algorithm(group_name, algorithm)
        metadata_key = _s3_key(paths["metadata"])
        if not fs.exists(metadata_key):
            raise FileNotFoundError(
                f"Missing metadata for {algorithm}; run the Stage B Train phase."
            )
        with fs.open(metadata_key, "r") as stream:
            metadata = ModelRegistry.read_metadata(stream)
        if (
            metadata.group != group_name
            or metadata.algorithm != algorithm
            or metadata.backend
            != config.anomaly_algorithm_backend_device(algorithm)[0]
            or metadata.feature_columns != ML_FEATURE_COLUMNS
        ):
            raise ValueError(f"Invalid or incompatible model metadata for {algorithm}.")

        detector_key = _s3_key(metadata.detector_path)
        scaler_key = _s3_key(metadata.scaler_path)
        if not fs.exists(detector_key) or not fs.exists(scaler_key):
            raise FileNotFoundError(f"Detector bundle is incomplete for {algorithm}.")
        detector = create_anomaly_detector(algorithm=algorithm)
        with fs.open(detector_key, "rb") as stream:
            detector.load(BytesIO(stream.read()))
        with fs.open(scaler_key, "rb") as stream:
            with np.load(BytesIO(stream.read()), allow_pickle=False) as state:
                detector.load_scaler_state(
                    {key: state[key] for key in state.files}
                )
        detector.load_backend_metadata(metadata.backend_metadata)

        calibration = None
        if len(expected_algorithms) > 1:
            if not metadata.calibration_path:
                raise FileNotFoundError(
                    f"Calibration scores are missing for ensemble member {algorithm}."
                )
            calibration_key = _s3_key(metadata.calibration_path)
            if not fs.exists(calibration_key):
                raise FileNotFoundError(
                    f"Calibration artifact is missing for ensemble member {algorithm}."
                )
            with fs.open(calibration_key, "rb") as stream:
                with np.load(BytesIO(stream.read()), allow_pickle=False) as state:
                    calibration = state["scores"].copy()
        loaded.append((algorithm, detector, metadata, calibration))
    return model_set, loaded


def train(feature_root: str, model_root: str) -> str:
    """Fit the configured detector set for every grouped training dataset."""
    feature_root = normalize_s3_folder(feature_root)
    model_root = normalize_s3_folder(model_root)
    print("=" * 70)
    print("LogHawk Stage B - TRAIN PHASE")
    print("=" * 70)
    fs = get_s3_filesystem()
    feature_folders = list_feature_folders(feature_root, fs)
    if not feature_folders:
        raise FileNotFoundError(
            f"No training feature groups found under: {feature_root}"
        )

    for folder in feature_folders:
        group_name = input_folder_name(folder)
        print(f"Training model for group: {group_name}")
        df = clean_features(load_features(folder, fs))
        if df.empty:
            raise ValueError(f"Training feature group is empty: {folder}")
        model_set_path = _s3_key(
            _model_registry(model_root).model_set_path(group_name)
        )
        if fs.exists(model_set_path):
            fs.rm(model_set_path)

        algorithms = list(config.LH_EFFECTIVE_ANOMALY_ALGORITHMS)
        for algorithm in algorithms:
            detector, _scaler = train_model(df, algorithm)
            print(
                f"Selected detector: algorithm={detector.algorithm}, "
                f"backend={detector.backend}, capabilities="
                f"{detector.capabilities.to_dict()}"
            )
            calibration_scores = None
            if len(algorithms) > 1:
                X_train = df[ML_FEATURE_COLUMNS].values
                calibration_scores, _flags = detector.detect(X_train)
            paths = _model_registry(model_root).paths_for_algorithm(
                group_name, algorithm
            )
            _save_detector_bundle(
                detector, paths, group_name, calibration_scores
            )
        _save_model_set(model_root, group_name)
    print()
    print("=" * 70)
    print("LogHawk Stage B - TRAIN PHASE Completed")
    print("=" * 70)
    print(f"Model output: {model_root}")
    return model_root


def detect(
    feature_root: str,
    anomaly_root: str,
    model_root: str,
) -> str:
    """Score grouped detection features using previously trained artifacts."""
    feature_root = normalize_s3_folder(feature_root)
    anomaly_root = normalize_s3_folder(anomaly_root)
    model_root = normalize_s3_folder(model_root)
    print("=" * 70)
    print("LogHawk Stage B - DETECT PHASE")
    print("=" * 70)
    fs = get_s3_filesystem()
    feature_folders = list_feature_folders(feature_root, fs)
    if not feature_folders:
        raise FileNotFoundError(
            f"No detection feature groups found under: {feature_root}"
        )

    failures = []
    for folder in feature_folders:
        group_name = input_folder_name(folder)
        try:
            df = clean_features(load_features(folder, fs))
            model_set, models = _load_saved_models(model_root, group_name, fs)
            if len(models) == 1:
                algorithm, model, metadata, _calibration = models[0]
                df = calculate_scores(df, model, None)
                df["detector_algorithms"] = algorithm
            else:
                raw_scores = {}
                for algorithm, model, _metadata, calibration in models:
                    scores, _flags = model.detect(
                        df[ML_FEATURE_COLUMNS].values
                    )
                    normalized = normalize_scores(scores, calibration)
                    raw_scores[algorithm] = normalized
                    column = "anomaly_score_" + algorithm.replace("-", "_")
                    df[column] = normalized
                combined, _normalized_scores = combine_normalized_scores(raw_scores)
                df["anomaly_score"] = combined
                df["is_anomaly"] = (
                    combined >= float(model_set["threshold"])
                )
                df["detector_algorithms"] = ",".join(
                    model_set["algorithms"]
                )
            burst_error = (
                (df["error_count"] >= 10)
                & (df["error_rate"] >= 0.5)
            )
            burst_http_5xx = (
                (df["http_5xx_count"] >= 10)
                & (df["http_5xx_rate"] >= 0.5)
            )
            df["is_anomaly"] = (
                df["is_anomaly"] | burst_error | burst_http_5xx
            )
            df = calculate_severity(df)
            df["reason"] = df.apply(generate_reason, axis=1)
            output_file = (
                anomaly_root + group_name + "/anomaly_results.parquet"
            )
            output_key_dir = output_file.replace("s3://", "", 1).rsplit("/", 1)[0]
            fs.makedirs(output_key_dir, exist_ok=True)
            save_results(df, output_file)
            print(f"\nANOMALY SUMMARY: {group_name}")
            print(df["severity"].value_counts())
            print(f"Feature windows: {len(df)}")
            print(f"Detected anomalies: {int(df['is_anomaly'].sum())}")
        except Exception as exc:
            failures.append((group_name, str(exc)))
            print(f"ERROR detecting group {group_name}: {type(exc).__name__}: {exc}")

    if failures:
        raise RuntimeError(f"Stage B detection failed for groups: {failures}")
    print()
    print("=" * 70)
    print("LogHawk Stage B - DETECT PHASE Completed")
    print("=" * 70)
    print(f"Anomaly output: {anomaly_root}")
    return anomaly_root


