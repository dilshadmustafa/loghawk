def train_model(baseline, algorithm_id: str | None = None):
    if algorithm_id is None:
        selected = config.LH_EFFECTIVE_ANOMALY_ALGORITHMS
        if len(selected) != 1:
            raise ValueError(
                "The standalone one-shot Stage B entry point supports one "
                "algorithm; use Temporal Train/Detect for ensembles."
            )
        algorithm_id = selected[0]
    X_train = baseline[ML_FEATURE_COLUMNS].values
    detector = create_anomaly_detector(algorithm=algorithm_id)
    print(f"Training detector: {detector.algorithm} (backend: {detector.backend})...")
    print(
        f"Detector: algorithm={detector.algorithm}, backend={detector.backend}, "
        f"capabilities={detector.capabilities.to_dict()}"
    )
    detector.train(X_train)

    print(
        f"Detector training completed: {detector.algorithm} "
        f"(backend: {detector.backend})"
    )

    return detector, None


# ============================================================
# Calculate anomaly score
# ============================================================


def calculate_scores(df, model, scaler):
    X = df[ML_FEATURE_COLUMNS].values
    if isinstance(model, AnomalyDetector):
        anomaly_score, is_anomaly = model.detect(X)
    else:
        # Compatibility for callers still passing the original sklearn pair.
        X_scaled = scaler.transform(X)
        anomaly_score = -model.score_samples(X_scaled)
        is_anomaly = model.predict(X_scaled) == -1
    df["anomaly_score"] = anomaly_score
    df["is_anomaly"] = is_anomaly

    return df


# ============================================================
# Convert anomaly score into severity
# ============================================================


def calculate_severity(df):
    """
    Convert Isolation Forest anomaly results into operational severity.

    NORMAL is assigned to every record classified as normal.

    WARNING / HIGH / CRITICAL are assigned only to records
    classified as anomalous.
    """
    df = df.copy()

    df["severity"] = "NORMAL"

    anomaly_mask = df["is_anomaly"]

    if not anomaly_mask.any():
        return df

    anomaly_scores = df.loc[
        anomaly_mask,
        "anomaly_score",
    ]

    q50 = anomaly_scores.quantile(0.50)
    q90 = anomaly_scores.quantile(0.90)
    q99 = anomaly_scores.quantile(0.99)

    anomaly_conditions = [
        anomaly_scores >= q99,
        anomaly_scores >= q90,
        anomaly_scores >= q50,
    ]

    anomaly_choices = [
        "CRITICAL",
        "HIGH",
        "WARNING",
    ]

    df.loc[anomaly_mask, "severity"] = np.select(
        anomaly_conditions,
        anomaly_choices,
        default="WARNING",
    )

    return df


