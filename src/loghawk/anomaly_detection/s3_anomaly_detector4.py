# ============================================================
# Process one Stage A input folder
# ============================================================


def process_input_folder(
    input_folder: str,
    output_root: str,
    identity_mapping_folder: str,
    fs,
):
    """
    Process one Stage A feature folder independently.

    Example:

        features/2026-09-28/container_logs/
            ->
        anomalies/2026-09-28/container_logs/
            anomaly_results.parquet
    """
    name = input_folder_name(input_folder)

    print()
    print("=" * 70)
    print(f"STAGE B INPUT: {name}")
    print("=" * 70)

    output_folder = derive_output_folder(
        input_folder,
        output_root,
    )

    output_file = (
        output_folder
        + "anomaly_results.parquet"
    )

    mapping, mapping_path = load_identity_mapping(
        input_folder,
        identity_mapping_folder,
        fs,
    )

    print(f"Feature input : {input_folder}")
    print(f"Identity map  : {mapping_path}")
    print(f"Anomaly output: {output_file}")

    # --------------------------------------------------------
    # 1. Load Stage A dataset
    # --------------------------------------------------------

    df = load_features(
        input_folder,
        fs,
    )

    # --------------------------------------------------------
    # 2. Validate optional identity mapping
    # --------------------------------------------------------

    validate_identity_mapping_against_features(
        mapping,
        mapping_path,
        df,
    )

    # --------------------------------------------------------
    # 3. Clean features
    # --------------------------------------------------------

    df = clean_features(df)

    # --------------------------------------------------------
    # 4. Select NORMAL baseline
    # --------------------------------------------------------

    baseline = select_normal_baseline(df)

    # --------------------------------------------------------
    # 5. Train model
    # --------------------------------------------------------

    model, scaler = train_model(baseline)

    # --------------------------------------------------------
    # 6. Score every feature window
    # --------------------------------------------------------

    df = calculate_scores(
        df,
        model,
        scaler,
    )

    # --------------------------------------------------------
    # 7. Calculate severity
    # --------------------------------------------------------

    df = calculate_severity(df)

    # --------------------------------------------------------
    # 8. Generate explanation
    # --------------------------------------------------------

    df["reason"] = df.apply(
        generate_reason,
        axis=1,
    )

    # --------------------------------------------------------
    # 9. Save model for this input dataset
    # --------------------------------------------------------

    artifact_paths = _group_model_paths(
        MODEL_PATH,
        name,
        model.backend,
        model.algorithm,
    )
    _save_group_artifacts(model, artifact_paths, name)
    _save_model_set(MODEL_PATH, name)

    # --------------------------------------------------------
    # 10. Save anomaly results
    # --------------------------------------------------------

    save_results(
        df,
        output_file,
    )

    # --------------------------------------------------------
    # 11. Print summary
    # --------------------------------------------------------

    anomalies = df[df["is_anomaly"]]

    print()
    print("=" * 70)
    print(f"ANOMALY SUMMARY: {name}")
    print("=" * 70)

    print(df["severity"].value_counts())

    print()
    print(f"Feature windows: {len(df)}")
    print(f"Detected anomalies: {len(anomalies)}")

    if not anomalies.empty:
        print()
        print("Top anomalies:")

        display_columns = [
            "timestamp",
            "entity_id",
            "anomaly_score",
            "severity",
            "reason",
        ]

        display_columns = [
            col
            for col in display_columns
            if col in anomalies.columns
        ]

        print(
            anomalies[display_columns]
            .sort_values("anomaly_score", ascending=False)
            .head(10)
            .to_string(index=False)
        )

    print()
    print(f"Stage B completed for: {name}")

    return output_file


