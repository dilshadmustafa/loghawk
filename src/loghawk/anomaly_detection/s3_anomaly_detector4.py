def normalize_s3_uri(path: str) -> str:
    """Convert Hadoop S3A URI to fsspec-compatible S3 URI."""
    if path.startswith("s3a://"):
        return "s3://" + path[len("s3a://"):]
    return path


def normalize_s3_folder(path: str) -> str:
    """Normalize an S3 folder URI so it has one trailing slash."""
    path = normalize_s3_uri(path)
    return path.rstrip("/") + "/"


def input_folder_name(feature_folder: str) -> str:
    """
    Return the Stage A input-folder name.

    Example:
        s3://bucket/features/2026-09-28/container_logs/
        -> container_logs
    """
    return feature_folder.rstrip("/").split("/")[-1]


def derive_identity_mapping_path(
    input_folder: str,
    identity_mapping_folder: str,
) -> str:
    """
    Derive the identity mapping corresponding to one Stage A input folder.

    Example:
        container_logs/
        ->
        identitymapping_container_logs.json
    """
    name = input_folder_name(input_folder)

    return (
        normalize_s3_folder(identity_mapping_folder)
        + f"identitymapping_{name}.json"
    )


def derive_output_folder(
    input_folder: str,
    output_root: str,
) -> str:
    """
    Derive the Stage B output folder for one Stage A input folder.
    """
    name = input_folder_name(input_folder)
    return normalize_s3_folder(output_root) + name + "/"


def derive_model_path(
    input_folder: str,
    model_root: str,
) -> tuple[str, str]:
    """
    Derive per-input model and scaler paths.
    """
    name = input_folder_name(input_folder)

    root = normalize_s3_folder(model_root)

    return (
        root + f"isolation_forest_{name}.joblib",
        root + f"isolation_scaler_{name}.joblib",
    )


def list_feature_folders(input_root: str, fs):
    """
    Enumerate the direct Stage A output folders.

    Expected layout:

        features/<date>/<inputfilename>/
            part-*.parquet
            ...

    Only direct child folders are returned. Internal Parquet files are handled
    by load_features().
    """
    input_root = normalize_s3_folder(input_root)
    prefix = input_root.replace("s3://", "").rstrip("/")

    entries = fs.ls(prefix, detail=True)

    folders = []

    for entry in entries:
        if isinstance(entry, dict):
            name = entry.get("name", "")
            entry_type = entry.get("type", "")
        else:
            name = str(entry)
            entry_type = ""

        if not name:
            continue

        if entry_type == "directory" or name.endswith("/"):
            folder = "s3://" + name.rstrip("/") + "/"
            folder_name = input_folder_name(folder)

            if folder_name.startswith("_") or folder_name.startswith("."):
                continue

            folders.append(folder)

    folders.sort()

    return folders


def validate_features(df: pd.DataFrame):
    """
    Verify that Stage A metadata and ML feature columns exist.

    entity_id is required because Stage A now uses generic entity identity.
    Optional identity metadata is preserved when present.
    """
    required_columns = [
        "timestamp",
        "entity_id",
        *ML_FEATURE_COLUMNS,
    ]

    missing = [
        column
        for column in required_columns
        if column not in df.columns
    ]

    if missing:
        raise ValueError(
            f"Missing required Stage A columns: {missing}"
        )


def load_identity_mapping(
    input_folder: str,
    identity_mapping_folder: str,
    fs,
):
    """
    Load the mapping for one input dataset if it exists.

    The mapping is optional for Stage B because Stage A already writes
    entity_id. If present, it is used for validation/context.
    """
    mapping_path = derive_identity_mapping_path(
        input_folder,
        identity_mapping_folder,
    )

    key = mapping_path.replace("s3://", "")

    if not fs.exists(key):
        print(
            f"Identity mapping not found; continuing without it: "
            f"{mapping_path}"
        )
        return None, mapping_path

    print(f"Reading identity mapping: {mapping_path}")

    with fs.open(key, "rb") as f:
        mapping = json.load(f)

    identity_mapping = mapping.get("identity_mapping", {})

    if not isinstance(identity_mapping, dict):
        raise ValueError(
            f"Invalid identity_mapping section in {mapping_path}"
        )

    return mapping, mapping_path


def validate_identity_mapping_against_features(
    mapping,
    mapping_path: str,
    df: pd.DataFrame,
):
    """
    Validate the optional mapping against Stage A feature output.

    Stage B does not use the mapping to construct entity_id; Stage A has already
    done that. This check prevents an inconsistent mapping from silently being
    accepted.
    """
    if mapping is None:
        return

    identity_mapping = mapping.get("identity_mapping", {})

    recommended_entity_column = identity_mapping.get(
        "recommended_entity_column"
    )

    if (
        recommended_entity_column
        and recommended_entity_column not in df.columns
    ):
        print(
            "Warning: identity mapping recommends "
            f"'{recommended_entity_column}', but that column is not present "
            "in the Stage A feature dataset. Stage B will continue using "
            "Stage A's entity_id."
        )


def load_features(input_folder: str, fs):
    """
    Load all Parquet files under one Stage A input folder.

    Example:
        s3://loghawk-data/features/2026-09-28/container_logs/
    """
    input_folder = normalize_s3_folder(input_folder)

    s3_prefix = input_folder.replace("s3://", "").rstrip("/")

    print(f"Reading features from: {input_folder}")

    # Stage A may have written or replaced these objects since this
    # filesystem instance cached the folder listing.
    fs.invalidate_cache(s3_prefix)
    parquet_files = fs.glob(
        f"{s3_prefix}/**/*.parquet"
    )

    if not parquet_files:
        raise FileNotFoundError(
            f"No Parquet files found under: {input_folder}"
        )

    dfs = []

    for file_path in parquet_files:
        print(f"Reading: {file_path}")

        with fs.open(file_path, "rb") as f:
            df = pd.read_parquet(f)

        dfs.append(df)

    if not dfs:
        raise ValueError(
            f"No feature data loaded from {input_folder}"
        )

    df = pd.concat(dfs, ignore_index=True)

    validate_features(df)

    return df


def clean_features(df):
    """
    Clean numeric Stage A features while preserving metadata.
    """
    df = df.copy()

    df["timestamp"] = pd.to_datetime(
        df["timestamp"],
        errors="coerce",
    )

    df["entity_id"] = (
        df["entity_id"]
        .fillna("unknown-entity")
        .astype(str)
    )

    for column in ML_FEATURE_COLUMNS:
        df[column] = pd.to_numeric(
            df[column],
            errors="coerce",
        )

    df[ML_FEATURE_COLUMNS] = (
        df[ML_FEATURE_COLUMNS]
        .replace([np.inf, -np.inf], np.nan)
        .fillna(0)
    )

    return df


# ============================================================
# Baseline selection
# ============================================================


def select_normal_baseline(df):
    """
    Select the earliest portion of the dataset as the normal baseline.

    Stage A uses timestamp as the one-minute aggregation timestamp.
    """
    if "timestamp" not in df.columns:
        raise ValueError(
            "Stage A feature dataset must contain a 'timestamp' column."
        )

    df = df.sort_values("timestamp").reset_index(drop=True)

    baseline_size = max(
        int(len(df) * BASELINE_RATIO),
        MIN_BASELINE_ROWS,
    )

    baseline_size = min(
        baseline_size,
        len(df),
    )

    baseline = df.iloc[:baseline_size].copy()

    print(
        f"Selected {len(baseline)} rows as normal baseline"
    )

    return baseline


