# Add human-readable explanation
# ============================================================


def generate_reason(row):
    reasons = []

    if row["error_rate"] > 0:
        reasons.append(
            f"error_rate={row['error_rate']:.2f}"
        )

    if row["http_5xx_count"] > 0:
        reasons.append(
            f"http_5xx={int(row['http_5xx_count'])}"
        )

    if row["timeout_count"] > 0:
        reasons.append(
            f"timeouts={int(row['timeout_count'])}"
        )

    if row["connection_error_count"] > 0:
        reasons.append(
            f"connection_errors="
            f"{int(row['connection_error_count'])}"
        )

    if row["authentication_failure_count"] > 0:
        reasons.append(
            f"auth_failures="
            f"{int(row['authentication_failure_count'])}"
        )

    if row["unique_exception_count"] > 0:
        reasons.append(
            f"unique_exceptions="
            f"{int(row['unique_exception_count'])}"
        )

    if not reasons:
        return "No significant anomaly indicators"

    return "; ".join(reasons)


