def _run_single_file(
    spark: SparkSession,
    input_path: str,
    output_path: str,
    identity_mapping_folder: str,
    select_temp_dir: str,
):
    """
    Process exactly one raw file.

    The file gets its own identity mapping and its own Parquet
    dataset under:

        features/<date>/<input_filename>/
    """

    identity_mapping_path = derive_identity_mapping_path(
        input_path,
        identity_mapping_folder,
    )

    mapping_document = load_identity_mapping(
        identity_mapping_path
    )

    print()
    print("=" * 70)
    print("LogHawk Stage A - Processing File")
    print("=" * 70)

    print("Input :", input_path)
    print("Mapping:", identity_mapping_path)
    print("Output:", output_path)

    # ========================================================
    # Read raw JSON and infer actual source schema
    # ========================================================

    spark_input_path = to_spark_s3_path(input_path)
    spark_output_path = to_spark_s3_path(output_path)

    if s3_select_enabled(input_path):
        # Mapping metadata already contains the sampled source columns. Use
        # it to avoid scanning the raw object with Spark before the Select
        # request. Role and identity fields are explicitly typed below.
        available_columns = mapping_document.get("source", {}).get(
            "column_names",
            [],
        )
        if not isinstance(available_columns, list) or not available_columns:
            raise ValueError(
                "S3 Select requires source.column_names in the identity "
                f"mapping: {identity_mapping_path}"
            )
        inferred_schema = StructType(
            [
                StructField(str(column), StringType(), True)
                for column in available_columns
            ]
        )
        print("Using mapping source columns for S3 Select schema:")
        print(available_columns)
    else:
        print()
        print("Inferring raw log schema from S3...")

        inferred_logs = (
            spark.read
            .option("samplingRatio", 0.1)
            .json(spark_input_path)
        )

        print()
        print("Inferred schema:")
        inferred_logs.printSchema()

        inferred_schema = inferred_logs.schema
        available_columns = inferred_logs.columns

        print()
        print("Raw columns:")
        print(available_columns)

    # ========================================================
    # Validate LLM identity mapping
    # ========================================================

    identity_columns = validate_identity_mapping(
        mapping=mapping_document["identity_mapping"],
        available_columns=available_columns,
    )

    field_mapping = validate_field_mapping(
        mapping_document.get("field_mapping"),
        available_columns,
    )

    if s3_select_enabled(input_path):
        print(
            "Reading records through RustFS S3 Select; filter:",
            config.LH_S3_SELECT_RECORD_FILTER,
        )
        filename = os.path.basename(input_path.rstrip("/"))
        selected_local_path = os.path.join(
            select_temp_dir,
            f"{filename}.selected.jsonl",
        )
        spark_input_path = materialize_s3_select_jsonl(
            input_path=input_path,
            output_path=selected_local_path,
            level_column=field_mapping["level_column"],
        )
    else:
        print(
            "S3 Select disabled or unsupported for this file; "
            "using the existing Spark S3 reader."
        )

    print()
    print("=" * 70)
    print("Validated identity mapping")
    print("=" * 70)

    if identity_columns:
        for index, column in enumerate(
            identity_columns,
            start=1,
        ):
            print(
                f"{index}. {column}"
            )
    else:
        print(
            "No valid identity columns found."
        )
        print(
            f"Using fallback entity_id: "
            f"{FALLBACK_ENTITY_ID}"
        )

    # ========================================================
    # Construct final PySpark schema
    # ========================================================

    schema = construct_schema(
        inferred_schema=inferred_schema,
        identity_columns=identity_columns,
        field_mapping=field_mapping,
    )

    # ========================================================
    # Read raw logs using constructed schema
    # ========================================================

    print()
    print("Reading raw logs using constructed schema...")

    logs = (
        spark.read
        .schema(schema)
        .json(spark_input_path)
    )

    # ========================================================
    # Standardize common fields
    # ========================================================

    timestamp_source = field_mapping["timestamp_column"]
    logs = logs.withColumn(
        "event_time",
        F.to_timestamp(F.col(timestamp_source)),
    )

    level_source = field_mapping["level_column"]
    level_value = (
        F.col(level_source).cast("string")
        if level_source
        else F.lit("UNKNOWN")
    )
    logs = logs.withColumn(
        "level",
        F.upper(F.trim(F.coalesce(level_value, F.lit("UNKNOWN")))),
    )

    message_source = field_mapping["message_column"]
    message_value = (
        F.col(message_source).cast("string")
        if message_source
        else F.lit("")
    )
    logs = logs.withColumn(
        "message",
        F.coalesce(message_value, F.lit("")),
    )

    exception_source = field_mapping["exception_column"]
    exception_value = (
        F.col(exception_source).cast("string")
        if exception_source
        else F.lit("")
    )
    logs = logs.withColumn(
        "exception",
        F.coalesce(exception_value, F.lit("")),
    )

    status_source = field_mapping["status_code_column"]
    status_value = (
        F.col(status_source).cast("int")
        if status_source
        else F.lit(None).cast("int")
    )
    logs = logs.withColumn("status_code", status_value)

    # ========================================================
    # Normalize identity columns
    # ========================================================

    for column in identity_columns:
        logs = logs.withColumn(
            column,
            F.when(
                F.col(column).isNotNull()
                & (
                    F.trim(
                        F.col(column)
                    ) != ""
                ),
                F.trim(
                    F.col(column)
                ),
            ).otherwise(None),
        )

    # ========================================================
    # Construct generic entity_id
    # ========================================================

    entity_id_expression = (
        build_entity_id_expression(
            identity_columns
        )
    )

    logs = logs.withColumn(
        "entity_id",
        entity_id_expression,
    )

    # ========================================================
    # Deterministic feature engineering
    # ========================================================

    logs = (
        logs

        .withColumn(
            "is_info",
            (
                F.col("level") == "INFO"
            ).cast("int"),
        )

        .withColumn(
            "is_warn",
            F.col("level")
            .isin(
                "WARN",
                "WARNING",
            )
            .cast("int"),
        )

        .withColumn(
            "is_error",
            (
                F.col("level") == "ERROR"
            ).cast("int"),
        )

        .withColumn(
            "is_http_4xx",
            (
                (F.col("status_code") >= 400)
                & (F.col("status_code") < 500)
            ).cast("int"),
        )

        .withColumn(
            "is_http_5xx",
            (
                (F.col("status_code") >= 500)
                & (F.col("status_code") < 600)
            ).cast("int"),
        )

        .withColumn(
            "is_timeout",
            F.when(
                F.lower(
                    F.col("message")
                ).contains("timeout"),
                1,
            ).otherwise(0),
        )

        .withColumn(
            "is_connection_error",
            F.when(
                F.lower(
                    F.col("message")
                ).rlike(
                    "connection refused|"
                    "connection reset|"
                    "connection failed"
                ),
                1,
            ).otherwise(0),
        )

        .withColumn(
            "is_auth_failure",
            F.when(
                F.lower(
                    F.col("message")
                ).rlike(
                    "authentication failed|"
                    "unauthorized|"
                    "invalid credentials|"
                    "login failed"
                ),
                1,
            ).otherwise(0),
        )
    )

    # ========================================================
    # Remove records with invalid timestamps
    # ========================================================

    logs = logs.filter(
        F.col("event_time").isNotNull()
    )

    # ========================================================
    # One-minute window
    # ========================================================

    logs = logs.withColumn(
        "window",
        F.window(
            F.col("event_time"),
            "1 minute",
        ),
    )

    # ========================================================
    # Aggregate by generic entity
    # ========================================================

    aggregation_expressions = []

    for column in identity_columns:
        aggregation_expressions.append(
            F.first(
                column,
                ignorenulls=True,
            ).alias(column)
        )

    aggregation_expressions.extend(
        [
            F.count("*").alias(
                "total_log_count"
            ),

            F.sum("is_info").alias(
                "info_count"
            ),

            F.sum("is_warn").alias(
                "warning_count"
            ),

            F.sum("is_error").alias(
                "error_count"
            ),

            F.sum("is_http_4xx").alias(
                "http_4xx_count"
            ),

            F.sum("is_http_5xx").alias(
                "http_5xx_count"
            ),

            F.sum("is_timeout").alias(
                "timeout_count"
            ),

            F.sum(
                "is_connection_error"
            ).alias(
                "connection_error_count"
            ),

            F.sum(
                "is_auth_failure"
            ).alias(
                "authentication_failure_count"
            ),

            F.countDistinct(
                F.when(
                    F.col("exception") != "",
                    F.col("exception"),
                )
            ).alias(
                "unique_exception_count"
            ),

            F.countDistinct(
                F.when(
                    F.col("level") == "ERROR",
                    F.col("message"),
                )
            ).alias(
                "unique_error_message_count"
            ),
        ]
    )

    features = (
        logs
        .groupBy(
            "entity_id",
            "window",
        )
        .agg(
            *aggregation_expressions
        )
    )

    # ========================================================
    # Window timestamp
    # ========================================================

    features = (
        features
        .withColumn(
            "timestamp",
            F.col("window.start"),
        )
        .drop("window")
    )

    # ========================================================
    # Rates
    # ========================================================

    features = (
        features

        .withColumn(
            "error_rate",
            F.when(
                F.col("total_log_count") > 0,
                F.col("error_count")
                / F.col("total_log_count"),
            ).otherwise(0.0),
        )

        .withColumn(
            "warning_rate",
            F.when(
                F.col("total_log_count") > 0,
                F.col("warning_count")
                / F.col("total_log_count"),
            ).otherwise(0.0),
        )

        .withColumn(
            "http_5xx_rate",
            F.when(
                F.col("total_log_count") > 0,
                F.col("http_5xx_count")
                / F.col("total_log_count"),
            ).otherwise(0.0),
        )

        .withColumn(
            "timeout_rate",
            F.when(
                F.col("total_log_count") > 0,
                F.col("timeout_count")
                / F.col("total_log_count"),
            ).otherwise(0.0),
        )
    )

    # ========================================================
    # Build final output columns
    # ========================================================

    metadata_columns = [
        "timestamp",
        "entity_id",
    ]

    for column in identity_columns:
        if column not in metadata_columns:
            metadata_columns.append(column)

    feature_columns = [
        "total_log_count",
        "info_count",
        "warning_count",
        "error_count",
        "error_rate",
        "warning_rate",
        "http_4xx_count",
        "http_5xx_count",
        "http_5xx_rate",
        "timeout_count",
        "timeout_rate",
        "connection_error_count",
        "authentication_failure_count",
        "unique_exception_count",
        "unique_error_message_count",
    ]

    final_columns = (
        metadata_columns
        + feature_columns
    )

    features = features.select(
        *final_columns
    )

    # ========================================================
    # Display results
    # ========================================================

    print()
    print("=" * 70)
    print("Generated feature dataset")
    print("=" * 70)

    features.orderBy(
        F.col("timestamp")
    ).show(
        20,
        truncate=False,
    )

    # ========================================================
    # Write per-file feature dataset
    # ========================================================

    print()
    print(
        "Writing feature data to S3..."
    )

    (
        features
        .write
        .mode("overwrite")
        .parquet(spark_output_path)
    )

    print()
    print("=" * 70)
    print("File feature generation completed")
    print("=" * 70)

    print()
    print("Raw input:")
    print(input_path)

    print()
    print("Identity mapping:")
    print(identity_mapping_path)

    print()
    print("Entity priority:")
    print(identity_columns)

    print()
    print("Feature output:")
    print(output_path)

    return output_path


def run(
    input_path: str,
    output_path: str,
):
    """
    Run LogHawk Stage A over a raw S3 folder.

    Example:

        input_path =
            s3://loghawk-data/raw/2026-09-28/

        output_path =
            s3://loghawk-data/features/2026-09-28/

    For every raw file:

        raw/<file>
             |
             +--> identitymapping/identitymapping_<file>.json
             |
             +--> features/<file>/

    Stage A does not start processing a file until its corresponding
    identity mapping exists.

    The function returns only after all files have been processed.
    """

    input_path = normalize_s3_folder(
        input_path
    )

    output_path = normalize_s3_folder(
        output_path
    )

    identity_mapping_folder = (
        derive_identity_mapping_folder(
            input_path
        )
    )
    phase = input_path.rstrip("/").rsplit("/", 1)[-1].upper()
    phase_label = "TRAIN PHASE" if phase == "TRAIN" else "DETECT PHASE"

    fs = create_s3_filesystem()

    raw_files = list_raw_files(
        input_path,
        fs,
    )

    if not raw_files:
        raise RuntimeError(
            "No supported raw log files found in:\n"
            f"{input_path}"
        )

    print()
    print("=" * 70)
    print(f"LogHawk Stage A - {phase_label}")
    print("=" * 70)

    print()
    print("Input folder:")
    print(input_path)

    print()
    print("Identity mapping folder:")
    print(identity_mapping_folder)

    print()
    print("Feature output folder:")
    print(output_path)

    print()
    print(f"Raw files found: {len(raw_files)}")

    for index, path in enumerate(
        raw_files,
        start=1,
    ):
        print(
            f"  {index}. {path}"
        )

    # ========================================================
    # Create ONE Spark session for the complete Stage A run.
    # ========================================================

    spark = (
        SparkSession.builder
        .appName(
            "LogHawk-FeatureEngineering-S3"
        )
        .master("local[1]")
        .config(
            "spark.jars.packages",
            "org.apache.hadoop:hadoop-aws:3.3.4",
        )
        .config(
            "spark.hadoop.fs.s3a.impl",
            "org.apache.hadoop.fs.s3a.S3AFileSystem",
        )
        .config(
            "spark.hadoop.fs.s3a.endpoint",
            config.LH_S3_ENDPOINT,
        )
        .config(
            "spark.hadoop.fs.s3a.access.key",
            config.LH_S3_ACCESS_KEY_ID,
        )
        .config(
            "spark.hadoop.fs.s3a.secret.key",
            config.LH_S3_SECRET_ACCESS_KEY,
        )
        .config(
            "spark.hadoop.fs.s3a.path.style.access",
            "true",
        )
        .config(
            "spark.hadoop.fs.s3a.connection.ssl.enabled",
            "false",
        )
        .config(
            "spark.hadoop.fs.s3a.aws.credentials.provider",
            "org.apache.hadoop.fs.s3a."
            "SimpleAWSCredentialsProvider",
        )
        .config(
            "spark.hadoop.fs.s3a.connection.timeout",
            "60000",
        )
        .config(
            "spark.hadoop.fs.s3a.connection.establish.timeout",
            "60000",
        )
        .config(
            "spark.hadoop.fs.s3a.threads.keepalivetime",
            "60",
        )
        .config(
            "spark.hadoop.fs.s3a.multipart.purge",
            "false",
        )
        .getOrCreate()
    )

    spark.sparkContext.setLogLevel("WARN")

    grouped_files = {}
    for raw_file in raw_files:
        filename = raw_file.rstrip("/").split("/")[-1]
        grouped_files.setdefault(source_group_name(filename), []).append(raw_file)

    print()
    print("Source groups:")
    for group_name, group_files in sorted(grouped_files.items()):
        print(f"  {group_name}: {len(group_files)} file(s)")
        for group_file in group_files:
            print(f"    - {group_file}")

    successful = []
    failed = []
    select_temp_dir = tempfile.mkdtemp(prefix="loghawk-s3-select-")

    try:
        for index, (group_name, group_files) in enumerate(
            sorted(grouped_files.items()), start=1,
        ):
            group_output_path = output_path + group_name + "/"
            print("\n" + "#" * 70)
            print(f"STAGE A GROUP {index} OF {len(grouped_files)}: {group_name}")
            print("#" * 70)
            try:
                normalized = []
                group_identity_columns = None
                for raw_file in group_files:
                    print(f"Reading group member: {raw_file}")
                    file_logs, identity_columns = _read_normalized_file(
                        spark=spark,
                        input_path=raw_file,
                        identity_mapping_folder=identity_mapping_folder,
                        select_temp_dir=select_temp_dir,
                    )
                    if group_identity_columns is None:
                        group_identity_columns = identity_columns
                    elif identity_columns != group_identity_columns:
                        raise ValueError(
                            f"Identity columns differ within source group '{group_name}': "
                            f"{group_identity_columns} vs {identity_columns} ({raw_file})"
                        )
                    normalized.append(file_logs)

                combined_logs = normalized[0]
                for file_logs in normalized[1:]:
                    combined_logs = combined_logs.unionByName(
                        file_logs, allowMissingColumns=True,
                    )

                features = _build_group_features(
                    combined_logs,
                    group_identity_columns or [],
                    group_name,
                )
                spark_output_path = to_spark_s3_path(group_output_path)
                print(f"Writing grouped features to: {group_output_path}")
                features.write.mode("overwrite").parquet(spark_output_path)
                successful.append(group_name)

            except Exception as exc:
                print()
                print(f"ERROR processing source group '{group_name}':")
                print(exc)
                failed.append((group_name, str(exc)))

        # ====================================================
        # Final Stage A status
        # ====================================================

        print()
        print("=" * 70)
        print(f"LogHawk Stage A - {phase_label} Completed")
        print("=" * 70)

        print(
            f"Total files:      {len(raw_files)}"
        )
        print(
            f"Source groups:    {len(grouped_files)}"
        )

        print(
            f"Successful:       {len(successful)}"
        )

        print(
            f"Failed:           {len(failed)}"
        )

        if failed:
            print()
            print("Failed source groups:")

            for path, error in failed:
                print()
                print(path)
                print(f"  {error}")

            raise RuntimeError(
                f"Stage A failed for "
                f"{len(failed)} source group(s)."
            )

        print()
        print(
            "All raw files were successfully processed."
        )

        print()
        print(
            "Feature output folder:"
        )
        print(
            output_path
        )

        return output_path

    finally:
        spark.stop()
        shutil.rmtree(select_temp_dir, ignore_errors=True)


