def _read_normalized_file(
    spark: SparkSession,
    input_path: str,
    identity_mapping_folder: str,
    select_temp_dir: str,
):
    """Read one source file, apply its mapping, and normalize role columns."""
    mapping_path = derive_identity_mapping_path(
        input_path,
        identity_mapping_folder,
    )
    mapping_document = load_identity_mapping(mapping_path)

    spark_input_path = to_spark_s3_path(input_path)
    if s3_select_enabled(input_path):
        available_columns = mapping_document.get("source", {}).get(
            "column_names", []
        )
        if not isinstance(available_columns, list) or not available_columns:
            raise ValueError(
                f"Mapping has no source.column_names: {mapping_path}"
            )
        inferred_schema = StructType([
            StructField(str(column), StringType(), True)
            for column in available_columns
        ])
    else:
        inferred = spark.read.option("samplingRatio", 0.1).json(
            spark_input_path
        )
        inferred_schema = inferred.schema
        available_columns = inferred.columns

    identity_columns = validate_identity_mapping(
        mapping_document["identity_mapping"],
        available_columns,
    )
    field_mapping = validate_field_mapping(
        mapping_document.get("field_mapping"),
        available_columns,
    )

    if s3_select_enabled(input_path):
        local_path = os.path.join(
            select_temp_dir,
            os.path.basename(input_path.rstrip("/")) + ".selected.jsonl",
        )
        spark_input_path = materialize_s3_select_jsonl(
            input_path,
            local_path,
            field_mapping["level_column"],
        )

    logs = spark.read.schema(
        construct_schema(
            inferred_schema,
            identity_columns,
            field_mapping,
        )
    ).json(spark_input_path)

    timestamp_source = field_mapping["timestamp_column"]
    logs = logs.withColumn(
        "event_time",
        F.to_timestamp(F.col(timestamp_source)),
    )

    level_source = field_mapping["level_column"]
    level_value = (
        F.col(level_source).cast("string")
        if level_source else F.lit("UNKNOWN")
    )
    logs = logs.withColumn(
        "level",
        F.upper(F.trim(F.coalesce(level_value, F.lit("UNKNOWN")))),
    )

    message_source = field_mapping["message_column"]
    message_value = (
        F.col(message_source).cast("string")
        if message_source else F.lit("")
    )
    logs = logs.withColumn("message", F.coalesce(message_value, F.lit("")))

    exception_source = field_mapping["exception_column"]
    exception_value = (
        F.col(exception_source).cast("string")
        if exception_source else F.lit("")
    )
    logs = logs.withColumn(
        "exception",
        F.coalesce(exception_value, F.lit("")),
    )

    status_source = field_mapping["status_code_column"]
    status_value = (
        F.col(status_source).cast("int")
        if status_source else F.lit(None).cast("int")
    )
    logs = logs.withColumn("status_code", status_value)

    for column in identity_columns:
        logs = logs.withColumn(
            column,
            F.when(
                F.col(column).isNotNull()
                & (F.trim(F.col(column)) != ""),
                F.trim(F.col(column)),
            ).otherwise(None),
        )

    logs = logs.withColumn(
        "entity_id",
        build_entity_id_expression(identity_columns),
    )

    selected_columns = list(dict.fromkeys([
        "event_time",
        "entity_id",
        *identity_columns,
        "level",
        "message",
        "exception",
        "status_code",
    ]))
    return logs.select(*selected_columns), identity_columns


def _build_group_features(logs, identity_columns: list[str], group_name: str):
    """Aggregate normalized rows from every file in one source group."""
    logs = (
        logs
        .withColumn("is_info", (F.col("level") == "INFO").cast("int"))
        .withColumn(
            "is_warn",
            F.col("level").isin("WARN", "WARNING").cast("int"),
        )
        .withColumn("is_error", (F.col("level") == "ERROR").cast("int"))
        .withColumn(
            "is_http_4xx",
            ((F.col("status_code") >= 400) & (F.col("status_code") < 500)).cast("int"),
        )
        .withColumn(
            "is_http_5xx",
            ((F.col("status_code") >= 500) & (F.col("status_code") < 600)).cast("int"),
        )
        .withColumn(
            "is_timeout",
            F.lower(F.col("message")).contains("timeout").cast("int"),
        )
        .withColumn(
            "is_connection_error",
            F.lower(F.col("message")).rlike(
                "connection refused|connection reset|connection failed"
            ).cast("int"),
        )
        .withColumn(
            "is_auth_failure",
            F.lower(F.col("message")).rlike(
                "authentication failed|unauthorized|invalid credentials|login failed"
            ).cast("int"),
        )
        .filter(F.col("event_time").isNotNull())
        .withColumn("window", F.window(F.col("event_time"), "1 minute"))
    )

    aggregations = [
        F.first(column, ignorenulls=True).alias(column)
        for column in identity_columns
    ]
    aggregations.extend([
        F.count("*").alias("total_log_count"),
        F.sum("is_info").alias("info_count"),
        F.sum("is_warn").alias("warning_count"),
        F.sum("is_error").alias("error_count"),
        F.sum("is_http_4xx").alias("http_4xx_count"),
        F.sum("is_http_5xx").alias("http_5xx_count"),
        F.sum("is_timeout").alias("timeout_count"),
        F.sum("is_connection_error").alias("connection_error_count"),
        F.sum("is_auth_failure").alias("authentication_failure_count"),
        F.countDistinct(
            F.when(F.col("exception") != "", F.col("exception"))
        ).alias("unique_exception_count"),
        F.countDistinct(
            F.when(F.col("level") == "ERROR", F.col("message"))
        ).alias("unique_error_message_count"),
    ])

    features = logs.groupBy("entity_id", "window").agg(*aggregations)
    features = (
        features
        .withColumn("timestamp", F.col("window.start"))
        .drop("window")
        .withColumn("source_group", F.lit(group_name))
    )

    for name, numerator in (
        ("error_rate", "error_count"),
        ("warning_rate", "warning_count"),
        ("http_5xx_rate", "http_5xx_count"),
        ("timeout_rate", "timeout_count"),
    ):
        features = features.withColumn(
            name,
            F.when(
                F.col("total_log_count") > 0,
                F.col(numerator) / F.col("total_log_count"),
            ).otherwise(0.0),
        )

    feature_columns = [
        "total_log_count", "info_count", "warning_count", "error_count",
        "error_rate", "warning_rate", "http_4xx_count", "http_5xx_count",
        "http_5xx_rate", "timeout_count", "timeout_rate",
        "connection_error_count", "authentication_failure_count",
        "unique_exception_count", "unique_error_message_count",
    ]
    metadata = ["timestamp", "entity_id", "source_group", *identity_columns]
    return features.select(*list(dict.fromkeys(metadata + feature_columns)))


