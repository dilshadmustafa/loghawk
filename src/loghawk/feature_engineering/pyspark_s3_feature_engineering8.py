def to_spark_s3_path(path: str) -> str:
    if path.startswith("s3://"):
        return "s3a://" + path[len("s3://"):]
    return path

def create_s3_filesystem() -> s3fs.S3FileSystem:
    """
    Create an S3/S3-compatible filesystem for reading the
    identity mapping JSON.

    The same credentials/endpoint used by Spark are taken from
    LogHawk configuration.
    """

    return s3fs.S3FileSystem(
        key=config.LH_S3_ACCESS_KEY_ID,
        secret=config.LH_S3_SECRET_ACCESS_KEY,
        client_kwargs={
            "endpoint_url": config.LH_S3_ENDPOINT,
        },
    )


def s3_select_enabled(path: str) -> bool:
    """S3 Select is limited here to enabled, uncompressed JSON objects."""
    filename = path.rstrip("/").lower()
    phase = path.rstrip("/").split("/")[-2].lower()
    phase_use = {
        "train": config.LH_S3_SELECT_USE_TRAIN_PHASE,
        "raw": config.LH_S3_SELECT_USE_DETECT_PHASE,
    }.get(phase, False)
    return (
        config.LH_S3_SELECT_SUPPORTED
        and phase_use
        and not filename.endswith((".gz", ".gzip"))
        and filename.endswith((".json", ".jsonl"))
    )


def materialize_s3_select_jsonl(
    input_path: str,
    output_path: str,
    level_column: str | None,
) -> str:
    """Write S3 Select's streamed JSONL records to a temporary local file."""
    parsed = urlparse(s3a_to_s3(input_path))
    if parsed.scheme != "s3" or not parsed.netloc or not parsed.path:
        raise ValueError(f"Invalid S3 object path: {input_path}")

    filters = config.LH_S3_SELECT_RECORD_FILTER_LIST
    expression = "SELECT * FROM S3Object s"
    if filters:
        if not level_column:
            raise ValueError(
                "S3 Select record filtering is enabled, but no valid log-level "
                "column is mapped. Set LH_S3_SELECT_RECORD_FILTER=ALL or "
                "provide a valid field mapping."
            )
        identifier = 's."' + level_column.replace('"', '""') + '"'
        filter_values = [
            alias
            for value in filters
            for alias in (("WARN", "WARNING") if value == "WARN" else (value,))
        ]
        literals = ", ".join(
            "'" + value.replace("'", "''") + "'"
            for value in filter_values
        )
        expression += f" WHERE upper(cast({identifier} as varchar)) IN ({literals})"

    client = boto3.client(
        "s3",
        endpoint_url=config.LH_S3_ENDPOINT,
        aws_access_key_id=config.LH_S3_ACCESS_KEY_ID,
        aws_secret_access_key=config.LH_S3_SECRET_ACCESS_KEY,
        region_name=config.LH_S3_REGION,
        config=BotoConfig(
            signature_version="s3v4",
            s3={"addressing_style": "path"},
        ),
    )
    response = client.select_object_content(
        Bucket=parsed.netloc,
        Key=parsed.path.lstrip("/"),
        ExpressionType="SQL",
        Expression=expression,
        InputSerialization={
            "JSON": {"Type": "LINES"},
            "CompressionType": "NONE",
        },
        OutputSerialization={
            "JSON": {"RecordDelimiter": "\n"},
        },
    )

    ended = False
    selected_row_count = 0
    pending = b""
    with open(output_path, "wb") as output_file:
        for event in response["Payload"]:
            if "Records" in event:
                payload = event["Records"]["Payload"]
                output_file.write(payload)
                lines = (pending + payload).split(b"\n")
                selected_row_count += sum(
                    1 for line in lines[:-1] if line.strip()
                )
                pending = lines[-1]
            elif "End" in event:
                ended = True

        if pending.strip():
            selected_row_count += 1

        if not ended:
            raise RuntimeError(
                f"S3 Select stream ended without an End event: {input_path}"
            )
        output_file.flush()
        output_file.seek(0, os.SEEK_END)
        if output_file.tell() and not _file_ends_with_newline(output_path):
            output_file.write(b"\n")

    if os.path.getsize(output_path) == 0:
        raise ValueError(
            "S3 Select returned no records for "
            f"{input_path} using filter {config.LH_S3_SELECT_RECORD_FILTER!r}"
        )
    print(f"Rows returned by S3 Select filter: {selected_row_count}")
    return Path(output_path).resolve().as_uri()


def _file_ends_with_newline(path: str) -> bool:
    with open(path, "rb") as input_file:
        input_file.seek(-1, os.SEEK_END)
        return input_file.read(1) == b"\n"


