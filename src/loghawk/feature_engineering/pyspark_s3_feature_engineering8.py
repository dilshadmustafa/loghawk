# Convert s3a:// -> s3://
# ============================================================

def s3a_to_s3(path: str) -> str:
    """
    s3fs expects s3:// while Spark uses s3a://.
    """

    if path.startswith("s3a://"):
        return "s3://" + path[len("s3a://"):]

    if path.startswith("s3://"):
        return path

    raise ValueError(
        f"Unsupported S3 path: {path}. "
        "Expected s3a:// or s3://."
    )


