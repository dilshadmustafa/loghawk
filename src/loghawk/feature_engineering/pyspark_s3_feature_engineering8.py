def normalize_s3_folder(path: str) -> str:
    """Ensure an S3 folder path ends with '/'."""
    if not (path.startswith("s3://") or path.startswith("s3a://")):
        raise ValueError(
            f"Unsupported S3 path: {path}. "
            "Expected s3:// or s3a://."
        )

    return path if path.endswith("/") else path + "/"


def derive_identity_mapping_folder(
    raw_input_folder: str,
) -> str:
    """
    Derive the phase-specific mapping root from:
        s3://bucket/<batch-folder>/{train|raw}/
    """
    raw_input_folder = normalize_s3_folder(raw_input_folder)

    scheme = (
        "s3a://"
        if raw_input_folder.startswith("s3a://")
        else "s3://"
    )

    path_without_scheme = re.sub(
        r"^s3a?://",
        "",
        raw_input_folder,
    )

    parts = path_without_scheme.split("/", 1)

    if len(parts) != 2:
        raise ValueError(
            f"Invalid S3 path: {raw_input_folder}"
        )

    bucket = parts[0]
    key = parts[1]

    key_parts = [p for p in key.split("/") if p]

    if len(key_parts) < 2 or key_parts[-1] not in {"train", "raw"}:
        raise ValueError(
            "Input folder must end in '/train/' or '/raw/':\n"
            f"{raw_input_folder}"
        )

    phase = key_parts[-1]
    batch_parts = key_parts[:-1]

    output_key = "/".join(
        [*batch_parts, "identitymapping", phase]
    ) + "/"

    return f"{scheme}{bucket}/{output_key}"


def derive_identity_mapping_path(
    raw_input_path: str,
    identity_mapping_folder: str | None = None,
) -> str:
    """
    Derive the identity mapping file for one raw input file.

    Example:

        Raw:
            s3://loghawk-data/raw/2026-09-28/container_logs.json

        Mapping:
            s3://loghawk-data/identitymapping/2026-09-28/
            identitymapping_container_logs.json
    """
    raw_input_path = raw_input_path.rstrip("/")

    if not (
        raw_input_path.startswith("s3://")
        or raw_input_path.startswith("s3a://")
    ):
        raise ValueError(
            "Raw input path must start with s3:// or s3a://"
        )

    if raw_input_path.endswith("/"):
        raise ValueError(
            "derive_identity_mapping_path() expects a file path, "
            "not a directory."
        )

    if identity_mapping_folder is None:
        # Derive mapping folder from the raw file path.
        path_without_scheme = re.sub(
            r"^s3a?://",
            "",
            raw_input_path,
        )
        parts = path_without_scheme.split("/", 1)

        if len(parts) != 2:
            raise ValueError(
                f"Invalid S3 path: {raw_input_path}"
            )

        bucket = parts[0]
        key = parts[1]
        key_parts = [p for p in key.split("/") if p]

        if len(key_parts) < 2 or key_parts[-2] not in {"train", "raw"}:
            raise ValueError(
                "Raw input file must be under a '/train/' or '/raw/' folder:\n"
                f"{raw_input_path}"
            )

        phase = key_parts[-2]
        batch_parts = key_parts[:-2]

        scheme = (
            "s3a://"
            if raw_input_path.startswith("s3a://")
            else "s3://"
        )

        identity_mapping_folder = (
            f"{scheme}{bucket}/"
            + "/".join([*batch_parts, "identitymapping", phase])
            + "/"
        )

    identity_mapping_folder = normalize_s3_folder(
        identity_mapping_folder
    )

    input_filename = raw_input_path.split("/")[-1]
    base_filename = input_file_stem(input_filename)
    group_name = source_group_name(input_filename)

    output_filename = (
        f"identitymapping_{base_filename}.json"
    )

    return identity_mapping_folder + group_name + "/" + output_filename


def input_file_stem(filename: str) -> str:
    """Remove one supported raw-file extension, including compound gzip suffixes."""
    supported_extensions = (
        ".jsonl.gz",
        ".json.gz",
        ".log.gz",
        ".jsonl",
        ".json",
        ".log",
    )
    lowered = filename.lower()
    for extension in supported_extensions:
        if lowered.endswith(extension):
            return filename[:-len(extension)]
    return os.path.splitext(filename)[0]


def source_group_name(filename: str) -> str:
    """Strip a trailing numeric sequence only when preceded by '_' or '-'."""
    stem = input_file_stem(filename)
    match = re.fullmatch(r"(.+)[_-]\d+", stem)
    return match.group(1) if match else stem


def list_raw_files(
    raw_input_folder: str,
    fs: s3fs.S3FileSystem,
) -> list[str]:
    """
    Enumerate supported raw log files directly under the input folder.
    """
    raw_input_folder = normalize_s3_folder(raw_input_folder)

    filesystem_path = s3a_to_s3(raw_input_folder)

    entries = fs.ls(
        filesystem_path,
        detail=True,
    )

    raw_files = []

    supported_extensions = (
        ".json",
        ".json.gz",
        ".jsonl",
        ".jsonl.gz",
        ".log",
        ".log.gz",
    )

    for entry in entries:
        if isinstance(entry, dict):
            entry_name = entry["name"]
            if entry.get("type") == "directory":
                continue
        else:
            entry_name = entry

        filename = entry_name.rstrip("/").split("/")[-1]

        if not filename:
            continue

        if filename.startswith("_") or filename.startswith("."):
            continue

        if not filename.lower().endswith(supported_extensions):
            print(
                f"Skipping unsupported file: {filename}"
            )
            continue

        raw_files.append(
            "s3://" + entry_name
            if not entry_name.startswith("s3://")
            else entry_name
        )

    raw_files.sort()
    return raw_files


