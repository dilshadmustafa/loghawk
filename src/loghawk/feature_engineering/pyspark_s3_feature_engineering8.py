# Read identity mapping JSON
# ============================================================

def load_identity_mapping(
    mapping_path: str,
) -> dict[str, Any]:
    """
    Read the complete identity and field mapping JSON from S3.
    """

    filesystem_path = s3a_to_s3(mapping_path)

    print()
    print("=" * 70)
    print("Reading identity mapping")
    print("=" * 70)

    print("Mapping:", mapping_path)

    fs = create_s3_filesystem()

    if not fs.exists(filesystem_path):
        raise FileNotFoundError(
            "Identity mapping JSON was not found:\n"
            f"{mapping_path}\n\n"
            "Run the Ollama identity-mapping step first."
        )

    with fs.open(
        filesystem_path,
        "r",
        encoding="utf-8",
    ) as f:

        mapping_document = json.load(f)

    # --------------------------------------------------------
    # The Ollama program writes:
    #
    # {
    #   "source": {...},
    #   "identity_mapping": {...},
    #   "field_mapping": {...}
    # }
    # --------------------------------------------------------

    if "identity_mapping" not in mapping_document:
        raise ValueError(
            "Invalid identity mapping JSON.\n"
            "Expected 'identity_mapping' section.\n"
            f"Path: {mapping_path}"
        )

    mapping = mapping_document["identity_mapping"]

    if not isinstance(mapping, dict):
        raise ValueError(
            "'identity_mapping' must be a JSON object."
        )

    return mapping_document


# ============================================================
# Validate identity mapping
# ============================================================

def validate_identity_mapping(
    mapping: dict[str, Any],
    available_columns: list[str],
) -> list[str]:
    """
    Validate the LLM-generated identity priority order against
    the actual raw input schema.

    Only columns that really exist in the input are allowed.

    Returns:
        Valid identity columns in priority order.
    """

    available = set(available_columns)

    priority_order = mapping.get(
        "priority_order",
        [],
    )

    if not isinstance(priority_order, list):
        raise ValueError(
            "identity_mapping.priority_order must be a list."
        )

    valid_columns = []

    for column in priority_order:

        if column in available:

            if column not in valid_columns:
                valid_columns.append(column)

        else:

            print(
                f"WARNING: Identity mapping contains column "
                f"'{column}', but it does not exist in the "
                f"raw input schema. Ignoring it."
            )

    # --------------------------------------------------------
    # If the LLM mapping contains identity_columns but omitted
    # something from priority_order, we can consider it as a
    # secondary candidate.
    # --------------------------------------------------------

    identity_columns = mapping.get(
        "identity_columns",
        [],
    )

    if isinstance(identity_columns, list):

        for column in identity_columns:

            if (
                column in available
                and column not in valid_columns
            ):
                valid_columns.append(column)

    return valid_columns


FIELD_ROLE_FALLBACKS = {
    "timestamp_column": "timestamp",
    "level_column": "level",
    "message_column": "message",
    "status_code_column": "status_code",
    "exception_column": "exception",
}


def validate_field_mapping(
    field_mapping: dict[str, Any] | None,
    available_columns: list[str],
) -> dict[str, str | None]:
    """Resolve field roles against the source schema, including legacy names."""
    if not isinstance(field_mapping, dict):
        field_mapping = {}
    available = set(available_columns)
    resolved = {}

    for role, fallback_column in FIELD_ROLE_FALLBACKS.items():
        column = field_mapping.get(role)

        if column is not None and (
            not isinstance(column, str)
            or column not in available
        ):
            print(
                f"WARNING: Field mapping {role}='{column}' is not in "
                "the source schema; checking the legacy field name."
            )
            column = None

        if column is None and fallback_column in available:
            column = fallback_column

        resolved[role] = column

    if resolved["timestamp_column"] is None:
        raise ValueError(
            "No valid timestamp field is mapped. "
            f"Available columns: {sorted(available)}"
        )

    return resolved


# ============================================================
# Construct dynamic Spark schema
# ============================================================

def construct_schema(
    inferred_schema: StructType,
    identity_columns: list[str],
    field_mapping: dict[str, str | None],
) -> StructType:
    """
    Construct a Spark schema dynamically from the actual raw
    input schema.

    Identity columns are forced to StringType because they may
    originate from different source systems and formats.

    Common LogHawk fields receive predictable types where
    appropriate.

    Unknown/source-specific fields are preserved using their
    inferred Spark data types.
    """

    identity_set = set(identity_columns)
    role_types = {
        field_mapping["timestamp_column"]: StringType(),
        field_mapping["level_column"]: StringType(),
        field_mapping["message_column"]: StringType(),
        field_mapping["exception_column"]: StringType(),
        field_mapping["status_code_column"]: IntegerType(),
    }

    fields = []

    for field in inferred_schema.fields:

        field_name = field.name

        # ----------------------------------------------------
        # Identity columns must be strings.
        # ----------------------------------------------------

        if field_name in identity_set:

            fields.append(
                StructField(
                    field_name,
                    StringType(),
                    True,
                )
            )

        elif field_name in role_types and role_types[field_name] is not None:
            fields.append(
                StructField(
                    field_name,
                    role_types[field_name],
                    True,
                )
            )

        # ----------------------------------------------------
        # Unknown source-specific columns retain their
        # inferred types.
        # ----------------------------------------------------

        else:

            fields.append(
                StructField(
                    field_name,
                    field.dataType,
                    field.nullable,
                )
            )

    return StructType(fields)


# ============================================================
# Construct entity_id expression
# ============================================================

def build_entity_id_expression(
    identity_columns: list[str],
):
    """
    Build the deterministic PySpark expression used to create
    entity_id from the LLM-generated priority order.
    """

    expressions = []

    for column in identity_columns:

        expressions.append(
            F.when(
                F.col(column).isNotNull()
                & (F.trim(F.col(column)) != ""),
                F.trim(F.col(column)),
            )
        )

    if not expressions:
        return F.lit(FALLBACK_ENTITY_ID)

    return F.coalesce(
        *expressions,
        F.lit(FALLBACK_ENTITY_ID),
    )


